using System.Text;
using System.Text.RegularExpressions;

namespace Factorio.ModTool.Build;

/// <summary>
/// Bundles the compatibility shim, <c>FactorioUtils.lua</c>, the emitted CSharp.lua modules, and the
/// entry-point invocation into a single self-contained <c>control.lua</c>.
/// </summary>
public static class LuaBundle
{
    public sealed record Result(
        string Lua,
        IReadOnlyList<string> Modules,
        IReadOnlyList<string> DroppedModules);

    private static readonly Regex UtilFunction = new(
        @"^function util\.([A-Za-z_][A-Za-z0-9_]*)",
        RegexOptions.Multiline | RegexOptions.Compiled);

    private static readonly Regex NamespaceDeclaration = new(
        @"System\.namespace\(""([^""]+)""",
        RegexOptions.Compiled);

    private static readonly Regex NestedNamespaceDeclaration = new(
        @"namespace\.namespace\(""([^""]+)""",
        RegexOptions.Compiled);

    /// <summary>
    /// Generates <c>local util_foo = util.foo</c> alias lines (grouped four per line) from the
    /// function definitions in <c>FactorioUtils.lua</c>.
    /// </summary>
    public static IReadOnlyList<string> UtilAliases(string utilsSource)
    {
        var names = UtilFunction.Matches(utilsSource)
            .Select(m => m.Groups[1].Value)
            .Distinct(StringComparer.Ordinal)
            .ToList();

        var lines = new List<string>();
        for (var i = 0; i < names.Count; i += 4)
        {
            var chunk = names.Skip(i).Take(4).ToList();
            var lhs = string.Join(", ", chunk.Select(n => "util_" + n));
            var rhs = string.Join(", ", chunk.Select(n => "util." + n));
            lines.Add($"local {lhs} = {rhs}");
        }

        return lines;
    }

    /// <summary>Bundles emitted CSharp.lua modules into a single Factorio <c>control.lua</c>.</summary>
    public static Result Bundle(
        string compatLuaPath,
        string utilsLuaPath,
        IReadOnlyList<string> modulePaths,
        string entryPoint)
    {
        var compat = File.ReadAllText(compatLuaPath).Replace("\r\n", "\n").TrimEnd();
        var utils = File.ReadAllText(utilsLuaPath).Replace("\r\n", "\n").TrimEnd();
        var aliases = UtilAliases(utils);

        var kept = new List<(string Name, string Code)>();
        var dropped = new List<string>();
        var droppedNamespaces = new HashSet<string>(StringComparer.Ordinal);

        foreach (var path in modulePaths)
        {
            var name = Path.GetFileNameWithoutExtension(path);
            if (name == "manifest") continue;

            var code = StripBanner(File.ReadAllText(path).Replace("\r\n", "\n"));
            if (IsNamespaceOnly(code))
            {
                dropped.Add(name);
                foreach (var ns in ExtractNamespaces(code))
                    droppedNamespaces.Add(ns);
            }
            else
            {
                kept.Add((name, code));
            }
        }

        var dot = entryPoint.LastIndexOf('.');
        if (dot <= 0 || dot == entryPoint.Length - 1)
            throw new ToolException($"entry '{entryPoint}' must be <Namespace>.<Class>.<Method>");

        var entryType = entryPoint[..dot];
        var entryMethod = entryPoint[(dot + 1)..];

        var sb = new StringBuilder();
        sb.AppendLine("-- Generated by factorio-mod. Do not edit by hand.");
        sb.AppendLine("local System = (function ()");
        sb.AppendLine(compat);
        sb.AppendLine("end)()");
        sb.AppendLine();
        sb.AppendLine("local util = (function ()");
        sb.AppendLine(utils);
        sb.AppendLine("end)()");
        foreach (var alias in aliases)
            sb.AppendLine(alias);
        sb.AppendLine();

        foreach (var ns in droppedNamespaces.OrderBy(n => n, StringComparer.Ordinal))
            sb.AppendLine($"System.namespace(\"{ns}\", function () end)");
        if (droppedNamespaces.Count > 0)
            sb.AppendLine();

        foreach (var (name, code) in kept)
        {
            sb.AppendLine($"-- module: {name}");
            sb.AppendLine("do");
            sb.AppendLine(code.TrimEnd());
            sb.AppendLine("end");
            sb.AppendLine();
        }

        sb.AppendLine("System.init()");
        sb.AppendLine($"System.get(\"{entryType}\").{entryMethod}()");

        return new Result(
            sb.ToString(),
            kept.Select(k => k.Name).ToList(),
            dropped);
    }

    private static bool IsNamespaceOnly(string code) =>
        !code.Contains(".class(\"", StringComparison.Ordinal) &&
        !code.Contains(".struct(\"", StringComparison.Ordinal) &&
        !code.Contains(".interface(\"", StringComparison.Ordinal) &&
        !code.Contains(".enum(\"", StringComparison.Ordinal);

    private static IEnumerable<string> ExtractNamespaces(string code)
    {
        foreach (Match match in NamespaceDeclaration.Matches(code))
        {
            var top = match.Groups[1].Value;
            yield return top;
            foreach (Match nested in NestedNamespaceDeclaration.Matches(code))
                yield return top + "." + nested.Groups[1].Value;
        }
    }

    private static string StripBanner(string lua)
    {
        var lines = lua.Split('\n');
        var index = 0;
        while (index < lines.Length && (lines[index].StartsWith("--", StringComparison.Ordinal) || string.IsNullOrWhiteSpace(lines[index])))
            index++;
        return string.Join("\n", lines.Skip(index));
    }
}
